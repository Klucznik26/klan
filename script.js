function setLanguage(language) {
  const selected = translations[language] ? language : "pl";
  const copy = translations[selected];
  const page = document.body.dataset.page || "home";

  document.documentElement.lang = selected;
  document.title = page === "advice" ? copy.advicePageTitle : copy.pageTitle;

  const description = document.querySelector('meta[name="description"]');
  if (description) {
    description.setAttribute("content", page === "advice" ? copy.adviceDescription : copy.description);
  }

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (copy[key] !== undefined) element.textContent = copy[key];
  });

  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const key = element.dataset.i18nHtml;
    if (copy[key] !== undefined) element.innerHTML = copy[key];
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (copy[key] !== undefined) element.setAttribute("alt", copy[key]);
  });

  document.querySelectorAll(".lang-button").forEach((button) => {
    const active = button.dataset.lang === selected;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  try {
    localStorage.setItem("klanLanguage", selected);
  } catch (_) {}
}

document.querySelectorAll(".lang-button").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

let initialLanguage = "pl";
try {
  initialLanguage = localStorage.getItem("klanLanguage") || "pl";
} catch (_) {}
setLanguage(initialLanguage);
